#!/usr/bin/env node
/* eslint-disable no-console */

/**
 * Branch Reconciliation Script
 * Part of: Git Workflow Constitution
 * 
 * Classifies all repository branches into:
 * - IN_MAIN: Work already merged
 * - CANONICAL: Active work not yet merged
 * - SUPERSEDED: Outdated branches replaced by newer work
 * - STALE: No commits in 30+ days
 */

const { execSync } = require('child_process');
const fs = require('fs');

function exec(command) {
  try {
    return execSync(command, { encoding: 'utf-8' }).trim();
  } catch (error) {
    return '';
  }
}

function getBranches() {
  const output = exec('git branch -r --format="%(refname:short)|%(committerdate:iso8601)"');
  if (!output) return [];
  
  return output
    .split('\n')
    .filter(line => line && !line.includes('HEAD'))
    .map(line => {
      const [name, date] = line.split('|');
      return { name: name.replace('origin/', ''), date: new Date(date) };
    });
}

function isInMain(branch) {
  // Check if branch commits are all in main
  const result = exec(`git log main..origin/${branch} --oneline`);
  return result === '';
}

function isStale(branchDate) {
  const thirtyDaysAgo = new Date();
  thirtyDaysAgo.setDate(thirtyDaysAgo.getDate() - 30);
  return branchDate < thirtyDaysAgo;
}

function classifyBranches() {
  console.log('🔍 Fetching latest from remote...');
  exec('git fetch --all --prune');
  
  console.log('\n📊 Analyzing branches...\n');
  
  const branches = getBranches().filter(b => b.name !== 'main');
  
  const classified = {
    IN_MAIN: [],
    CANONICAL: [],
    SUPERSEDED: [],
    STALE: []
  };
  
  for (const branch of branches) {
    if (isInMain(branch.name)) {
      classified.IN_MAIN.push(branch.name);
    } else if (isStale(branch.date)) {
      classified.STALE.push({ name: branch.name, lastCommit: branch.date.toISOString() });
    } else {
      classified.CANONICAL.push({ name: branch.name, lastCommit: branch.date.toISOString() });
    }
  }
  
  return classified;
}

function generateReport(classified) {
  const report = `# Branch Reconciliation Report
Generated: ${new Date().toISOString()}

## Summary
- **Total branches:** ${Object.values(classified).reduce((sum, arr) => sum + arr.length, 0)}
- **In main:** ${classified.IN_MAIN.length}
- **Canonical (active):** ${classified.CANONICAL.length}
- **Stale (30+ days):** ${classified.STALE.length}
- **Superseded:** ${classified.SUPERSEDED.length}

## 🟢 IN_MAIN (Safe to delete)
${classified.IN_MAIN.length > 0 ? classified.IN_MAIN.map(b => `- ${b}`).join('\n') : '*None*'}

## 🔵 CANONICAL (Active work)
${classified.CANONICAL.length > 0 ? classified.CANONICAL.map(b => `- ${b.name} (last: ${b.lastCommit.split('T')[0]})`).join('\n') : '*None*'}

## 🟡 STALE (Review needed)
${classified.STALE.length > 0 ? classified.STALE.map(b => `- ${b.name} (last: ${b.lastCommit.split('T')[0]})`).join('\n') : '*None*'}

## 🔴 SUPERSEDED (Safe to delete)
${classified.SUPERSEDED.length > 0 ? classified.SUPERSEDED.map(b => `- ${b}`).join('\n') : '*None*'}

---
*Generated by: scripts/branch-reconciliation.js*
`;
  
  return report;
}

function main() {
  console.log('═══════════════════════════════════════════════════════════');
  console.log('  GIT WORKFLOW CONSTITUTION — BRANCH RECONCILIATION');
  console.log('═══════════════════════════════════════════════════════════\n');
  
  const classified = classifyBranches();
  const report = generateReport(classified);
  
  // Write report
  const reportPath = 'branch-reconciliation-report.md';
  fs.writeFileSync(reportPath, report);
  
  console.log(report);
  console.log(`\n✅ Report saved to: ${reportPath}\n`);
  
  // Summary
  console.log('═══════════════════════════════════════════════════════════');
  console.log('  SUMMARY');
  console.log('═══════════════════════════════════════════════════════════');
  console.log(`  Safe to delete: ${classified.IN_MAIN.length} branches`);
  console.log(`  Active work: ${classified.CANONICAL.length} branches`);
  console.log(`  Needs review: ${classified.STALE.length} branches`);
  console.log('═══════════════════════════════════════════════════════════\n');
}

if (require.main === module) {
  main();
}

module.exports = { classifyBranches, generateReport };
