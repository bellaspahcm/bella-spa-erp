# Move functions
function Move-FilesSafely {
    param(
        [string]$DestFolder,
        [string[]]$FileList
    )
    
    $moved = 0
    $skipped = 0
    
    foreach ($file in $FileList) {
        $sourcePath = ".\$file"
        $destPath = ".\$DestFolder\$file"
        
        if (Test-Path $sourcePath) {
            try {
                Move-Item -Path $sourcePath -Destination $destPath -Force
                $moved++
                Write-Host "✓ Moved: $file" -ForegroundColor Green
            } catch {
                Write-Host "✗ Error moving $file : $_" -ForegroundColor Red
            }
        } else {
            $skipped++
            Write-Host "○ Skipped (not found): $file" -ForegroundColor Yellow
        }
    }
    
    Write-Host "`n$DestFolder Summary: $moved moved, $skipped skipped" -ForegroundColor Cyan
}

